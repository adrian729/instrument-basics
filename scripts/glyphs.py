"""The music glyphs the staves draw (the treble clef, sharp, flat and whole note), as SVG paths, and the
engraving defaults they're drawn with (the staff's and ledger lines' thickness, how far a ledger line
reaches past a note), from Bravura, the SMuFL reference font (SIL Open Font License,
scripts/OFL-Bravura.txt), and its metadata, into src/views/glyphs.ts.

Everything is in the font's units (1000 to the em, y up), a staff space a quarter of the em, as in every
SMuFL font. Each glyph is drawn at SMuFL's origin: the clef's on its G line, the note's and the
accidentals' on the note's line or space, each glyph's left edge at x = 0.

    curl -LO https://github.com/steinbergmedia/bravura/raw/master/redist/otf/Bravura.otf
    curl -LO https://github.com/steinbergmedia/bravura/raw/master/redist/Bravura.json
    uv run -q scripts/glyphs.py Bravura.otf Bravura.json
"""

import json
import sys
from pathlib import Path

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.ttLib import TTFont

# Each glyph's SMuFL name and code point.
GLYPHS = {"clef": ("gClef", 0xE050), "sharp": ("accidentalSharp", 0xE262), "flat": ("accidentalFlat", 0xE260), "whole": ("noteheadWhole", 0xE0A2)}
# The engraving defaults used, by their SMuFL names, in staff spaces in the metadata.
ENGRAVING = {"staffLine": "staffLineThickness", "legerLine": "legerLineThickness", "legerExtension": "legerLineExtension"}


def main(font_path: str, metadata_path: str) -> None:
    font, meta = TTFont(font_path), json.loads(Path(metadata_path).read_text())
    cmap, glyphs = font.getBestCmap(), font.getGlyphSet()
    space = font["head"].unitsPerEm / 4
    out = {}
    for name, (smufl, code) in GLYPHS.items():
        glyph = glyphs[cmap[code]]
        path, bounds = SVGPathPen(glyphs, ntos=lambda v: f"{v:g}"), BoundsPen(glyphs)
        glyph.draw(path)
        glyph.draw(bounds)
        x0, y0, x1, y1 = bounds.bounds
        # The outline's bounds are the metadata's, to the unit.
        box = meta["glyphBBoxes"][smufl]
        assert all(abs(a - b * space) <= 1 for a, b in zip((x0, y0, x1, y1), (*box["bBoxSW"], *box["bBoxNE"]))), smufl
        out[name] = {"d": path.getCommands(), "x0": x0, "x1": x1, "y0": y0, "y1": y1}
    engraving = {"space": space, **{name: meta["engravingDefaults"][key] * space for name, key in ENGRAVING.items()}}
    lines = [
        f"// Generated by scripts/glyphs.py from Bravura {meta['fontVersion']} and its SMuFL metadata (SIL Open Font License,",
        "// scripts/OFL-Bravura.txt). In the font's units, y up: a staff space is a quarter of the em. Each glyph at",
        "// SMuFL's origin (the clef's on its G line, a note's and an accidental's on the note's line or space, the",
        "// left edge at 0), with its bounds x0..x1 and y0..y1.",
        "export type Glyph = { d: string; x0: number; x1: number; y0: number; y1: number };",
        f"export const GLYPHS: Record<{' | '.join(json.dumps(n) for n in GLYPHS)}, Glyph> = {{",
    ]
    lines += [f"  {name}: {json.dumps(g)}," for name, g in out.items()]
    lines += [
        "};",
        "// The font's engraving defaults: the staff space, the staff's and ledger lines' thickness, and how far a",
        "// ledger line reaches past the note on each side.",
        f"export const ENGRAVING = {json.dumps(engraving)} as const;",
        "",
    ]
    target = Path(__file__).resolve().parent.parent / "src" / "views" / "glyphs.ts"
    target.write_text("\n".join(lines))
    print(f"wrote {target}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
