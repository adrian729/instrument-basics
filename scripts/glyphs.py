"""The music glyphs the staves draw (the treble clef, sharp, flat and whole note), as SVG paths, from
Noto Music (SIL Open Font License, scripts/OFL-NotoMusic.txt), into src/views/glyphs.ts.

The paths are in the font's units (1000 to the em, y up). Its staff lines are 244 apart, the bottom
one's centre at y = 12; the clef sits on that staff as drawn at the origin, and the note and the
accidentals are drawn for the first space (F4), centred at y = 134.

    curl -LO https://github.com/google/fonts/raw/main/ofl/notomusic/NotoMusic-Regular.ttf
    uv run -q scripts/glyphs.py NotoMusic-Regular.ttf
"""

import json
import sys
from pathlib import Path

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.ttLib import TTFont

GLYPHS = {"clef": 0x1D11E, "sharp": 0x266F, "flat": 0x266D, "whole": 0x1D15D}


def main(font_path: str) -> None:
    font = TTFont(font_path)
    cmap, glyphs = font.getBestCmap(), font.getGlyphSet()
    out = {}
    for name, code in GLYPHS.items():
        glyph = glyphs[cmap[code]]
        path, bounds = SVGPathPen(glyphs, ntos=lambda v: f"{v:g}"), BoundsPen(glyphs)
        glyph.draw(path)
        glyph.draw(bounds)
        x0, y0, x1, y1 = bounds.bounds
        out[name] = {"d": path.getCommands(), "x0": x0, "x1": x1, "y0": y0, "y1": y1}
    lines = [
        "// Generated by scripts/glyphs.py from Noto Music (SIL Open Font License, scripts/OFL-NotoMusic.txt).",
        "// Paths in the font's units, y up; x0..x1 and y0..y1 are each glyph's bounds.",
        "export type Glyph = { d: string; x0: number; x1: number; y0: number; y1: number };",
        f"export const GLYPHS: Record<{' | '.join(json.dumps(n) for n in GLYPHS)}, Glyph> = {{",
    ]
    lines += [f"  {name}: {json.dumps(g)}," for name, g in out.items()]
    lines += ["};", ""]
    target = Path(__file__).resolve().parent.parent / "src" / "views" / "glyphs.ts"
    target.write_text("\n".join(lines))
    print(f"wrote {target}")


if __name__ == "__main__":
    main(sys.argv[1])
